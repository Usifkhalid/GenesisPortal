/**
 * storage.js — where uploaded files live, behind a small adapter.
 *
 * Two adapters, chosen by STORAGE_DRIVER:
 *   local  a folder outside frontend/ (STORAGE_DIR, default <repo>/storage,
 *          gitignored), for development
 *   azure  one private Azure Blob container (storage-azure.js), for production
 * Either way nothing uploaded is ever served as a static file or by a public
 * link: the only way out is a route that checks the session.
 *
 *   put(key, buffer)   → void
 *   get(key)           → Buffer | null
 *   remove(key)        → void, quietly when the key is already gone
 *   check()            → void; throws when the store cannot be used (/api/ready)
 *
 * The app never uses an adapter bare: lib/file-scan.js wraps it, so a file is
 * only read back once it has been scanned and found clean.
 *
 * Keys are generated by the server (never from client input) and are checked
 * again here against a strict pattern, so a key can never leave the folder.
 */

import { constants } from 'node:fs';
import { access, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { appEnv, runtime } from '../config/runtime.js';
import { createAzureBlobStorage } from './storage-azure.js';

const KEY = /^[a-z0-9][a-z0-9._-]{0,150}$/;

export function assertKey(key) {
  if (typeof key !== 'string' || !KEY.test(key) || key.includes('..')) {
    throw new Error('Invalid storage key.');
  }
}

/** @param {string} dir  an absolute folder */
export function createLocalStorage(dir) {
  const fileOf = (key) => {
    assertKey(key);
    return path.join(dir, key);
  };

  return {
    async put(key, buffer) {
      const file = fileOf(key);
      await mkdir(dir, { recursive: true });
      await writeFile(file, buffer);
    },
    async get(key) {
      try {
        return await readFile(fileOf(key));
      } catch (err) {
        if (err.code === 'ENOENT') return null;
        throw err;
      }
    },
    async remove(key) {
      await rm(fileOf(key), { force: true });
    },
    async check() {
      await mkdir(dir, { recursive: true });
      await access(dir, constants.R_OK | constants.W_OK);
    },
  };
}

/**
 * The adapter the configuration asks for.
 * @param {object} [config]  the environment, or a test's version of it
 */
export function defaultStorage(config = appEnv()) {
  return config.STORAGE_DRIVER === 'azure'
    ? createAzureBlobStorage(config)
    : createLocalStorage(
        path.resolve(runtime().storageBase, config.STORAGE_DIR ?? runtime().storageDefault)
      );
}

/** An in-memory adapter for tests. `files` is exposed to look inside. */
export function createMemoryStorage() {
  const files = new Map();
  return {
    files,
    async put(key, buffer) {
      assertKey(key);
      files.set(key, Buffer.from(buffer));
    },
    async get(key) {
      assertKey(key);
      return files.get(key) ?? null;
    },
    async remove(key) {
      assertKey(key);
      files.delete(key);
    },
    async check() {},
  };
}
